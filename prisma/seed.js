/** สร้างข้อมูลชุด Rodlex ทั้งหมด — เรียกหลังสร้างผู้ใช้แล้ว */
async function seedRodlex(users) {
  // --- ทีมช่าง ---
  console.log("🧑‍🔧 สร้างทีมช่าง...");
  for (const [i, t] of TECHNICIANS.entries()) {
    await db.technician.create({
      data: {
        code: t.code,
        name: t.name,
        bio: t.bio,
        skills: t.skills,
        category: t.category,
        province: t.province,
        online: t.online,
        jobsDone: t.jobsDone,
        rating: t.rating,
        reviewCount: t.reviewCount,
        featured: !!t.featured,
        imageJson: t.image,
        createdAt: daysAgo(120 - i * 5),
      },
    });
  }

  // --- ข่าว (publishedAt กระจายย้อนหลังไม่เกิน 60 วัน) ---
  console.log("📰 สร้างข่าว...");
  for (const n of NEWS) {
    await db.newsArticle.create({
      data: {
        title: n.title,
        excerpt: n.excerpt,
        body: n.body,
        group: n.group,
        tags: n.tags,
        imageJson: n.image,
        videoUrl: null,
        publishedAt: daysAgo(n.daysAgo),
      },
    });
  }

  // --- กระทู้ + ตอบกลับ + ถูกใจ (likeCount ต้องเท่ากับจำนวน ForumLike จริง) ---
  console.log("💬 สร้างกระทู้ถาม-ตอบ...");
  const at = (idx) => users[idx % users.length];
  for (const t of THREADS) {
    const likeUserIds = [...new Set(t.likeIdx.map((i) => at(i).id))];
    const thread = await db.forumThread.create({
      data: {
        authorId: at(t.authorIdx).id,
        title: t.title,
        body: t.body,
        category: t.category,
        imagesJson: t.images.length
          ? JSON.stringify(t.images.map((s) => JSON.parse(s)))
          : null,
        likeCount: likeUserIds.length,
        createdAt: hoursAgo(t.hoursAgo),
      },
    });
    for (const r of t.replies) {
      await db.forumReply.create({
        data: {
          threadId: thread.id,
          authorId: at(r.authorIdx).id,
          body: r.body,
          createdAt: hoursAgo(r.hoursAgo),
        },
      });
    }
    for (const userId of likeUserIds) {
      await db.forumLike.create({ data: { threadId: thread.id, userId } });
    }
  }

  // --- ตำแหน่งงาน + ใบสมัคร ---
  console.log("💼 สร้างตำแหน่งงาน...");
  for (const j of JOBS) {
    const job = await db.jobPosting.create({
      data: {
        title: j.title,
        type: j.type,
        location: j.location,
        wage: j.wage,
        description: j.description,
        active: true,
        createdAt: daysAgo(j.daysAgo),
      },
    });
    for (const a of j.applications) {
      await db.jobApplication.create({
        data: {
          jobId: job.id,
          name: a.name,
          phone: a.phone,
          note: a.note,
          createdAt: daysAgo(a.daysAgo),
        },
      });
    }
  }

  // --- คำขอเรียกช่าง ---
  console.log("🛠️ สร้างคำขอเรียกช่าง...");
  for (const s of SERVICE_REQUESTS) {
    await db.serviceRequest.create({
      data: {
        name: s.name,
        phone: s.phone,
        machineType: s.machineType,
        problem: s.problem,
        province: s.province,
        status: s.status,
        createdAt: hoursAgo(s.hoursAgo),
      },
    });
  }

  // --- ตรวจความสอดคล้อง: likeCount ต้องตรงกับจำนวน ForumLike จริง ---
  const threads = await db.forumThread.findMany({
    include: { _count: { select: { likes: true, replies: true } } },
  });
  for (const t of threads) {
    if (t.likeCount !== t._count.likes)
      throw new Error(
        `likeCount ไม่ตรงกับจำนวน like จริงของกระทู้ "${t.title}" (${t.likeCount} vs ${t._count.likes})`,
      );
  }
  const replyTotal = threads.reduce((s, t) => s + t._count.replies, 0);
  console.log(
    `  ✅ กระทู้ ${threads.length} · ตอบกลับ ${replyTotal} · ถูกใจ ${threads.reduce((s, t) => s + t.likeCount, 0)} (likeCount ตรงกับ ForumLike ทุกกระทู้)`,
  );
}

